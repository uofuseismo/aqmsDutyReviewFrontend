#!/usr/bin/env node
/*
  Turns FirstInfoCities.csv into the TypeScript the app bakes in.

    node scripts/build-firstinfo-cities.mjs sample-data/FirstInfoCities.csv

  The list changes a few times a decade, so it is compiled into the bundle
  rather than fetched: a press release should not depend on one more request
  succeeding. Re-run this when the CSV changes and commit the output.

  Expects the header POINT_X,POINT_Y,City - longitude, latitude, name - with
  the name quoted when it contains a comma ("Helena, MT").
*/
import { readFileSync, writeFileSync } from 'node:fs'

const input = process.argv[2]
if (!input) {
  console.error('usage: build-firstinfo-cities.mjs <FirstInfoCities.csv>')
  process.exit(1)
}

/** One CSV line into fields, honouring double quotes. */
function fields(line) {
  const out = []
  let field = ''
  let quoted = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') { field += '"'; i++ }
      else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') { out.push(field); field = '' }
    else field += c
  }
  out.push(field)
  return out
}

const lines = readFileSync(input, 'utf8').split(/\r?\n/).filter((l) => l.trim() !== '')
const header = fields(lines[0]).map((h) => h.trim())
const [ix, iy, iname] = ['POINT_X', 'POINT_Y', 'City'].map((h) => header.indexOf(h))
if (ix < 0 || iy < 0 || iname < 0) {
  console.error(`expected POINT_X, POINT_Y and City columns, found: ${header.join(', ')}`)
  process.exit(1)
}

const rows = lines.slice(1).map((line, n) => {
  const f = fields(line)
  const longitude = Number(f[ix])
  const latitude = Number(f[iy])
  const name = (f[iname] ?? '').trim()
  if (!Number.isFinite(longitude) || !Number.isFinite(latitude) || name === '') {
    console.error(`line ${n + 2} is not a usable place: ${line}`)
    process.exit(1)
  }
  return [latitude, longitude, name]
})

const body = rows.map(([lat, lon, name]) => `  [${lat}, ${lon}, ${JSON.stringify(name)}],`).join('\n')
const output = `/*
  GENERATED by scripts/build-firstinfo-cities.mjs from FirstInfoCities.csv.
  Do not edit by hand - change the CSV and re-run the script.

  The places a press release measures an epicentre from. [latitude,
  longitude (degrees east, signed), name], ${rows.length} of them.
*/
export const FIRST_INFO_CITIES: ReadonlyArray<readonly [number, number, string]> = [
${body}
]
`
writeFileSync('src/features/pressRelease/firstInfoCities.ts', output)
console.log(`wrote ${rows.length} places to src/features/pressRelease/firstInfoCities.ts`)
